        <h3 style="text-align: center;">Sobre a Capivara (<em>Hydrochoerus hydrochaeris</em>)</h3>

        <h4>🌟 Visão Geral</h4>
        <p>A capivara é o <strong>maior roedor do mundo</strong>, pertencente à família dos cavídeos. Nativa de todas as regiões da América do Sul (exceto no extremo sul e em áreas de grande altitude), ela é um mamífero altamente adaptado à vida semiaquática, transitando com facilidade entre a terra firme, rios, lagos e pântanos.</p>

        <h4>🌿 Características Principais</h4>
        <ul>
            <li><strong>Porte Físico:</strong> Adultos podem pesar entre 35 kg e 65 kg (com casos excepcionais ultrapassando essa marca) e medir até 1,30 metro de comprimento.</li>
            <li><strong>Adaptações Aquáticas:</strong> Seus olhos, orelhas e narinas ficam posicionados na parte superior da cabeça, permitindo que ela respire e observe o ambiente enquanto nada. Possui também uma pequena membrana interdigital nas patas.</li>
            <li><strong>Alimentação:</strong> É um animal <strong>herbívoro estrito</strong>, alimentando-se principalmente de capim, gramíneas e plantas aquáticas. Também pratica a cecotrofia (reingestão de fezes especiais) para extrair o máximo de nutrientes de sua dieta fibrosa.</li>
        </ul>

        <h4>🐾 Comportamento e Sociedade</h4>
        <ul>
            <li><strong>Vida em Grupo:</strong> Vive em bandos familiares que variam de 10 a 20 indivíduos, liderados por um macho dominante.</li>
            <li><strong>Temperamento Dócil:</strong> É mundialmente famosa por sua serenidade incomparável, tolerando a presença de outras espécies — incluindo aves, macacos e até predadores — sem demonstrar agressividade.</li>
            <li><strong>Comunicação Sonora:</strong> Utiliza uma variedade de sons, como roncos, assobios e estalos de dentes, para alertar o grupo sobre perigos ou manter o contato visual e auditivo.</li>
        </ul>

        <h4>💻 Fenômeno Cultural</h4>
        <p>Graças à sua expressão impassível e convivência pacífica com o mundo ao seu redor, a capivara transformou-se em um <strong>ícone global da internet</strong>. Ela estrela centenas de memes e é considerada um símbolo de relaxamento e harmonia.</p>
        
        <p><em>Curiosidade:</em> Sendo uma excelente nadadora, a capivara utiliza a água como seu principal refúgio para escapar de predadores terrestres (como onças e jacarés) e para regular a temperatura corporal nos dias mais quentes.</p>
        
